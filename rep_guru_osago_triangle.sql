WITH 
-- Агрегация по 4 полям (для Экспозиции)
agg_4 AS (
    SELECT 
        "Тип страхователя",
        "Признак пролонгации",
        "Месяц действия",
        "Месяц календарный",
        SUM("Экспозиция") AS "Сумма_Экспозиции"
    FROM "Данные_RS"
    GROUP BY 
        "Тип страхователя",
        "Признак пролонгации",
        "Месяц действия",
        "Месяц календарный"
),
-- Агрегация по 5 полям (для MCL)
agg_5 AS (
    SELECT 
        "Тип страхователя",
        "Признак пролонгации",
        "Месяц действия",
        "Месяц календарный",
        "Отв_Пр",
        SUM("MCL") AS "Сумма_MCL"
    FROM "Данные_RS"
    GROUP BY 
        "Тип страхователя",
        "Признак пролонгации",
        "Месяц действия",
        "Месяц календарный",
        "Отв_Пр"
),
-- Создаем Emblem из уникальных комбинаций (если его нет)
Emblem AS (
    SELECT DISTINCT
        "Тип страхователя",
        "Признак пролонгации",
        "Месяц действия",
        "Месяц календарный",
        "Отв_Пр"
    FROM "Данные_RS"
)
-- Основной запрос с JOIN
SELECT 
    e."Тип страхователя",
    e."Признак пролонгации",
    e."Месяц действия",
    e."Месяц календарный",
    e."Отв_Пр",
    COALESCE(a4."Сумма_Экспозиции", 0) AS "Сумма_Экспозиции",
    COALESCE(a5."Сумма_MCL", 0) AS "Сумма_MCL"
FROM Emblem e
LEFT JOIN agg_4 a4 ON 
    a4."Тип страхователя" = e."Тип страхователя"
    AND a4."Признак пролонгации" = e."Признак пролонгации"
    AND a4."Месяц действия" = e."Месяц действия"
    AND a4."Месяц календарный" = e."Месяц календарный"
LEFT JOIN agg_5 a5 ON 
    a5."Тип страхователя" = e."Тип страхователя"
    AND a5."Признак пролонгации" = e."Признак пролонгации"
    AND a5."Месяц действия" = e."Месяц действия"
    AND a5."Месяц календарный" = e."Месяц календарный"
    AND a5."Отв_Пр" = e."Отв_Пр"
ORDER BY 
    e."Тип страхователя",
    e."Признак пролонгации",
    e."Месяц действия",
    e."Месяц календарный",
    e."Отв_Пр";
