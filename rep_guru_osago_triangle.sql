-- Создаем таблицу Emblem
CREATE TABLE Emblem AS
SELECT DISTINCT
    "Тип страхователя",
    "Признак пролонгации",
    "Месяц действия",
    "Месяц календарный",
    "Отв_Пр"
FROM "Данные_RS";

-- Затем считаем суммы
SELECT 
    e.*,
    COALESCE(
        (SELECT SUM(d."Экспозиция")
         FROM "Данные_RS" d
         WHERE d."Тип страхователя" = e."Тип страхователя"
           AND d."Признак пролонгации" = e."Признак пролонгации"
           AND d."Месяц действия" = e."Месяц действия"
           AND d."Месяц календарный" = e."Месяц календарный"),
        0
    ) AS "Сумма_Экспозиции",
    
    COALESCE(
        (SELECT SUM(d."MCL")
         FROM "Данные_RS" d
         WHERE d."Тип страхователя" = e."Тип страхователя"
           AND d."Признак пролонгации" = e."Признак пролонгации"
           AND d."Месяц действия" = e."Месяц действия"
           AND d."Месяц календарный" = e."Месяц календарный"
           AND d."Отв_Пр" = e."Отв_Пр"),
        0
    ) AS "Сумма_MCL"
FROM Emblem e;
